def transcribe_gradio_audio(audio_tuple):
    if not audio_tuple:
        return "未錄製任何聲音。"
    samplerate, audio_np = audio_tuple
    if audio_np is None:
        return "錄音資料為空。"
    try:
        with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as f:
            temp_wav = f.name
        seg = AudioSegment(
            audio_np.tobytes(),
            frame_rate=samplerate,
            sample_width=audio_np.dtype.itemsize,
            channels=1
        )
        seg.export(temp_wav, format="wav")
        if speech_config is None:
            return "Speech config 未初始化，無法辨識。"
        speech_config.speech_recognition_language = "zh-TW"
        audio_cfg = speechsdk.audio.AudioConfig(filename=temp_wav)
        recognizer = speechsdk.SpeechRecognizer(speech_config=speech_config, audio_config=audio_cfg)
        result = recognizer.recognize_once_async().get()
        try:
            os.remove(temp_wav)
        except:
            pass
        if result.reason == speechsdk.ResultReason.RecognizedSpeech:
            return result.text
        else:
            cd = result.cancellation_details
            return f"辨識失敗: {cd.reason} {cd.error_details if hasattr(cd, 'error_details') else ''}"
    except Exception as e:
        return f"音訊處理錯誤: {e}"

