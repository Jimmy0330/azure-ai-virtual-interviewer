def analyze_resume_with_azure(resume_text):
    if not resume_text:
        return [], []
    if text_analytics_client is None:
        return ["錯誤：Language client 未初始化"], []
    try:
        kp_result = text_analytics_client.extract_key_phrases(documents=[resume_text])
        key_phrases = kp_result[0].key_phrases if not kp_result[0].is_error else []
        ents_result = text_analytics_client.recognize_entities(documents=[resume_text])
        entities = []
        if not ents_result[0].is_error:
            for ent in ents_result[0].entities:
                if ent.category in ["Skill", "JobTitle", "Organization", "Person"]:
                    entities.append((ent.text, ent.category))
        return key_phrases, entities
    except Exception as e:
        return [f"文字分析錯誤: {e}"], []

