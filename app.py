def generate_resume_visual(resume_text):
    # 1. 設定參數
    api_base = OPENAI_API_BASE.rstrip("/")
    api_key = OPENAI_API_KEY
    deployment_name = "dall-e-3"
    api_version = "2024-02-01"

    if not resume_text:
        return None

    # 2. 準備 Prompt (截斷以符合長度限制)
    safe_text = resume_text[:400].replace("\n", " ")
    prompt = f"Create a modern, clean, professional resume UI design layout. No text details, just visual structure. Context: {safe_text}"

    # 3. 拼接正確的 Azure URL
    # 格式: https://{ResourceName}.openai.azure.com/openai/deployments/{DeploymentName}/images/generations?api-version={Version}
    url = f"{api_base}/openai/deployments/{deployment_name}/images/generations?api-version={api_version}"

    headers = {
        "api-key": api_key,
        "Content-Type": "application/json"
    }

    body = {
        "prompt": prompt,
        "size": "1024x1024",
        "n": 1,
        "quality": "standard", # DALL-E 3 選項
        "style": "natural"     # DALL-E 3 選項
    }

    print(f"🎨 [Direct API] 正在請求: {url}")

    try:
        # 4. 直接發送 POST 請求
        response = requests.post(url, headers=headers, json=body)

        # 5. 檢查回應
        if response.status_code == 200:
            result = response.json()
            # 解析 Azure 回傳的 JSON 結構
            image_url = result['data'][0]['url']
            print("✅ 圖片生成成功！")
            return image_url
        else:
            # 印出錯誤代碼與訊息
            print(f"❌ API 請求失敗 [Code {response.status_code}]: {response.text}")
            return None

    except Exception as e:
        print(f"❌ 發生例外錯誤: {e}")
        return None
