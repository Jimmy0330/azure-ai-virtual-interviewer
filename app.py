last_call_time = 0
last_face_result = "⏳ 等待分析..."

def analyze_face(frame):
    print("DeepFace analyze_face running")
    global last_call_time, last_face_result
    now = time.time()

    # 每 1.5 秒分析一次（DeepFace 夠快）
    if now - last_call_time < 1.5:
        return last_face_result

    last_call_time = now

    try:
        if frame is None:
            last_face_result = "❌ 沒有影像"
            return last_face_result

        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        faces = face_cascade.detectMultiScale(
            gray,
            scaleFactor=1.3,
            minNeighbors=5,
            minSize=(60, 60)
        )

        if len(faces) == 0:
            last_face_result = "😶 未偵測到人臉"
            return last_face_result

        x, y, w, h = faces[0]
        face_roi = frame[y:y+h, x:x+w]

        last_face_result = "🧠 表情分析中..."

        result = DeepFace.analyze(
            img_path=face_roi,
            actions=["emotion"],
            enforce_detection=False
        )

        emo = result[0]["dominant_emotion"]
        emo_scores = result[0]["emotion"]

        nervous_score = (
            emo_scores["fear"] * 0.45 +
            emo_scores["sad"] * 0.30 +
            emo_scores["neutral"] * 0.15 +
            emo_scores["angry"] * 0.10
        )

        INTERVIEW_CONTEXT["emotion_log"].append({
            "time": time.strftime("%H:%M:%S"),
            "dominant": result[0]["dominant_emotion"],
            "nervous": round(nervous_score, 2)
        })
        last_face_result = f"🙂 情緒：{result[0]['dominant_emotion']}｜緊張度 {nervous_score:.1f}"


        return last_face_result

    except Exception as e:
        last_face_result = f"❌ 錯誤：{e}"
        return last_face_result



